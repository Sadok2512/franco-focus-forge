import { chromium } from 'playwright';
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import assert from 'node:assert/strict';
const out=process.env.BC2_PROOF_DIR ?? 'audit/bc2-lot-b';
fs.mkdirSync(out,{recursive:true});
const password=execFileSync('docker',['exec','bc4-api-1','python','-c','import os; print(os.environ["BC4_ADMIN_PASSWORD"],end="")'],{encoding:'utf8'});
const browser=await chromium.launch({args:['--no-sandbox']});
const page=await browser.newPage({viewport:{width:1720,height:1080}});
page.setDefaultTimeout(60000);
const responses=[],pending=[],errors=[];
page.on('pageerror',e=>errors.push(e.message));
page.on('response',r=>{if(r.url().includes('/dict/v2/')&&r.ok())pending.push(r.json().then(body=>responses.push({url:r.url(),at:new Date().toISOString(),body})).catch(()=>{}));});
try{
 await page.goto('http://localhost:5174/login');
 await page.waitForTimeout(2000);
 await page.getByLabel('Adresse e-mail').fill('admin@bc4.local');
 await page.locator('input[autocomplete="current-password"]').fill(password);
 await page.getByRole('button',{name:'Se connecter',exact:true}).click();
 await page.waitForURL(/\/projects/);
 await page.locator('tr').filter({has:page.getByText('TEST2',{exact:true})}).getByRole('button',{name:'Ouvrir',exact:true}).click();
 await page.locator('nav a').filter({hasText:'Dictionnaire RRC'}).click();
 await page.getByTestId('dict-catalog-v22').waitFor({timeout:180000});
 assert.match(await page.locator('header').first().innerText(),/v1\.37\.0/);
 assert.equal(await page.locator('[data-testid^="catalog-category-LTE-"]').count(),12);
 await page.locator('header').first().screenshot({path:`${out}/00-header.png`});
 await page.screenshot({path:`${out}/01-categories.png`,fullPage:true});
 const search=page.getByTestId('dict-tree-search');
 await search.fill('timeToTrigger');
 const param=page.getByTestId('catalog-param-timeToTrigger').filter({hasText:'[A1]'});
 await param.waitFor();
 assert.match(await param.innerText(),/\[A2\]/);assert.match(await param.innerText(),/\[A5\]/);
 assert.match(await param.innerText(),/RRCReconf/);
 await page.screenshot({path:`${out}/02-mobility.png`,fullPage:true});
 const aggregate=param.getByRole('checkbox',{name:'Sélectionner le paramètre timeToTrigger',exact:true});
 await aggregate.check();
 await page.getByTestId('dict-chart-timeToTrigger').waitFor({timeout:180000});
 await page.getByTestId('dict-chart-timeToTrigger').locator('canvas').waitFor();
 assert.match(await page.getByTestId('dict-chart-timeToTrigger').innerText(),/n=\s*512/);
 await page.screenshot({path:`${out}/04-aggregate.png`,fullPage:true});
 const child=param.getByTestId('catalog-leaf').first().getByRole('checkbox');
 await child.uncheck();
 assert.equal(await aggregate.getAttribute('aria-checked'),'mixed');
 await aggregate.check();
 await search.fill('q-RxLevMin');
 for(const label of ['SIB1','SIB3','SIB5'])assert((await page.getByTestId('dict-catalog-v22').innerText()).includes(label));
 await page.screenshot({path:`${out}/03-idle.png`,fullPage:true});
 await search.fill('');
 await page.getByText('Filtres avancés',{exact:true}).click();
 await page.getByLabel('Message',{exact:true}).selectOption('SystemInformation - SIB2');
 await page.getByRole('button',{name:'Appliquer les filtres',exact:true}).click();
 await page.waitForURL(/rrc_message=/);
 await page.getByText('Filtres avancés',{exact:true}).click();
 await search.fill('additionalSpectrumEmission');
 const filtered=page.getByTestId('catalog-param-additionalSpectrumEmission');
 await filtered.getByRole('checkbox',{name:'Sélectionner le paramètre additionalSpectrumEmission',exact:true}).check();
 await page.getByTestId('dict-chart-additionalSpectrumEmission').waitFor({timeout:180000});
 assert.match(await page.getByTestId('dict-chart-additionalSpectrumEmission').innerText(),/n=\s*103/);
 assert((await page.getByTestId('dict-catalog-v22').innerText()).includes('SIB2'));
 await page.screenshot({path:`${out}/05-message-sib2.png`,fullPage:true});
 // Clear Message before checking the existing template linkage.
 await page.getByText('Filtres avancés',{exact:true}).click();
 await page.getByLabel('Message',{exact:true}).selectOption('');
 await page.getByRole('button',{name:'Appliquer les filtres',exact:true}).click();
 await page.waitForURL(url=>!url.searchParams.has('rrc_message'));
 await page.getByText('Filtres avancés',{exact:true}).click();
 await search.fill('');
 await page.getByRole('tab',{name:'Templates',exact:true}).click();
 await page.locator('#rrc-panel-templates button').filter({hasText:/^PHY/}).click();
 await page.getByRole('tab',{name:'Paramètres',exact:true}).waitFor();
 assert.equal(await page.getByRole('tab',{name:'Paramètres',exact:true}).getAttribute('aria-selected'),'true');
 assert(await page.locator('#rrc-panel-catalog input[type=checkbox]:checked').count()>0);
 await page.screenshot({path:`${out}/06-template-link.png`,fullPage:true});
 await Promise.all(pending);
 assert.deepEqual(errors,[]);
 fs.writeFileSync(`${out}/browser-responses.json`,JSON.stringify(responses,null,2));
 fs.writeFileSync(`${out}/browser-result.txt`,'PASS: login UI TEST2, categories, messages, aggregate n=512, partial selection, SIB2 n=103, template linkage.\n');
 console.log('PASS lot B');
}catch(e){await page.screenshot({path:`${out}/failure.png`,fullPage:true});fs.writeFileSync(`${out}/failure.txt`,(await page.locator('body').innerText())+'\n'+String(e)+'\n'+errors.join('\n'));throw e;}
finally{await browser.close();}
