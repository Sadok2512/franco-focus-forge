import { chromium } from 'playwright';
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import assert from 'node:assert/strict';
const out=process.env.BC2_PROOF_DIR ?? 'audit/bc2-lot-a';
fs.mkdirSync(out,{recursive:true});
const password=execFileSync('docker',['exec','bc4-api-1','python','-c','import os; print(os.environ["BC4_ADMIN_PASSWORD"],end="")'],{encoding:'utf8'});
const browser=await chromium.launch({args:['--no-sandbox']});
const page=await browser.newPage({viewport:{width:1720,height:1080}});
const responses=[],pending=[];
page.on('response',r=>{if(r.url().includes('/dict/v2/distribution') || /\/projects\/134af70a06eb$/.test(r.url())) pending.push(r.json().then(body=>responses.push({url:r.url(),at:new Date().toISOString(),status:r.status(),headers:{Authorization:'Bearer <admin@bc4.local session>'},body})));});
page.on('pageerror', e=>console.log('PAGEERROR',e.message));
try {
 await page.goto('http://localhost:5174/login');
 await page.waitForTimeout(2000);
 await page.getByLabel('Adresse e-mail').fill('admin@bc4.local');
 await page.locator('input[autocomplete="current-password"]').fill(password);
 await page.getByRole('button',{name:'Se connecter',exact:true}).click();
 await page.waitForURL(/\/projects/,{timeout:60000});
 const row=page.locator('tr').filter({has:page.getByText('TEST2',{exact:true})});
 await row.getByRole('button',{name:'Ouvrir',exact:true}).click();
 await page.locator('nav a').filter({hasText:/Dictionnaire/}).first().click();
 await page.getByTestId('dict-tree-search').waitFor({timeout:60000});
 assert.match(await page.locator('body').innerText(),/v1\.36\.2/);
 await page.locator('header').first().screenshot({path:`${out}/00-header.png`});
 await page.getByTestId('dict-tree-search').fill('phich-Duration');
 await page.getByTestId('dict-leaf-phich-Duration').first().waitFor({timeout:180000});
 await page.getByTestId('dict-leaf-phich-Duration').first().getByRole('checkbox').check();
 await page.getByTestId('dict-chart-phich-Duration').waitFor({timeout:180000});
 await Promise.all([page.waitForResponse(r=>r.url().includes('/dict/v2/distribution') && r.url().includes('group_by=operator_band'),{timeout:180000}),page.getByTestId('dict-groupby-operator_band').click()]);
 await page.waitForTimeout(1000);
 fs.writeFileSync(`${out}/ui-inspect.txt`,await page.locator('body').innerText());
 assert.match(await page.getByTestId('dict-chart-phich-Duration').innerText(),/1 valeur · n=4/);
 assert.equal(await page.locator('.rrc-filter-period').innerText(),'Période : 2026-10-15 → 2026-10-15');
 await page.screenshot({path:`${out}/01-period-and-search.png`,fullPage:true});
 await page.getByTestId('dict-tree-search').fill('rsrpResult');
 await page.getByTestId('dict-leaf-rsrpResult').filter({hasText:/1\s*515/}).getByRole('checkbox').check();
 await page.getByTestId('dict-chart-rsrpResult').waitFor({timeout:180000});
 assert.match(await page.getByTestId('dict-chart-rsrpResult').innerText(),/Distribution indisponible/);
 await page.screenshot({path:`${out}/02-both-api-gap.png`,fullPage:true});
 await page.getByRole('tab',{name:'Raw parameter',exact:true}).click();
 await page.getByTestId('dict-tree-search').fill('measId');
 await page.getByTestId('dict-raw-leaf-measId').first().waitFor({timeout:180000});
 await page.screenshot({path:`${out}/03-raw-api-gap.png`,fullPage:true});
 await Promise.all(pending);
 fs.writeFileSync(`${out}/browser-responses.json`,JSON.stringify(responses,null,2));
 console.log('Login UI, TEST2 selected, dictionary search captured.');
} catch(e) {fs.writeFileSync(`${out}/ui-error.txt`,await page.locator('body').innerText());await page.screenshot({path:`${out}/error.png`});throw e;} finally {await browser.close();}
